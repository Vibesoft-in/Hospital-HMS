#!/usr/bin/env node
import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const lock = JSON.parse(readFileSync(join(root, "package-lock.json"), "utf8"));

const direct = [];
for (const [name, version] of Object.entries(pkg.dependencies ?? {})) {
  direct.push({ name, version, scope: "production", declaredIn: "dependencies" });
}
for (const [name, version] of Object.entries(pkg.devDependencies ?? {})) {
  direct.push({ name, version, scope: "development", declaredIn: "devDependencies" });
}

const transitive = [];
for (const [location, meta] of Object.entries(lock.packages ?? {})) {
  if (!location.startsWith("node_modules/")) continue;
  const name = meta.name ?? location.replace(/^node_modules\//, "").replace(/\/node_modules\//g, "/");
  if (pkg.dependencies?.[name] || pkg.devDependencies?.[name]) continue;
  transitive.push({
    name,
    version: meta.version ?? null,
    license: meta.license ?? null,
    scope: "transitive",
  });
}

transitive.sort((a, b) => a.name.localeCompare(b.name));
direct.sort((a, b) => a.name.localeCompare(b.name));

const inventory = {
  generatedAt: new Date().toISOString(),
  project: pkg.name,
  projectVersion: pkg.version,
  lockfileVersion: lock.lockfileVersion,
  summary: {
    directProduction: Object.keys(pkg.dependencies ?? {}).length,
    directDevelopment: Object.keys(pkg.devDependencies ?? {}).length,
    lockfilePackages: Object.keys(lock.packages ?? {}).length,
    transitive: transitive.length,
  },
  direct,
  note: "Full transitive tree is in package-lock.json and the CycloneDX SBOM generated by `npm run sbom` (inventory/sbom.cdx.json).",
};

const outDir = join(root, "inventory");
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, "npm-inventory.json"), JSON.stringify(inventory, null, 2));
console.log(
  `Wrote inventory/npm-inventory.json (${inventory.summary.directProduction} prod, ${inventory.summary.directDevelopment} dev, ${transitive.length} transitive)`
);
